#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	n;
	char	display[11];
	int		i;

	n = nb;
	if (n == 0)
		write(1, "0", 1);
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	i = 0;
	while (n > 0)
	{
		display[i] = n % 10 + '0';
		n /= 10;
		i++;
	}
	while (i > 0)
	{
		write(1, &display[--i], 1);
	}
}
